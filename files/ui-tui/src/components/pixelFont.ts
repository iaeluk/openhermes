const GLYPH_W = 8;
const GLYPH_H = 8;
const GAP = 2;

const glyphRows = (ch: string): number[] => PIXEL_GLYPHS[ch] ?? PIXEL_GLYPHS['?'] ?? [0, 0, 0, 0, 0, 0, 0, 0];

/** Render text as crisp half-block rows (8px font, 1x — square pixels). */
export const renderPixelName = (text: string): string[] => {
  const chars = [...text].map(glyphRows);
  const px: number[][] = [];

  for (let r = 0; r < GLYPH_H; r++) {
    const row: number[] = [];
    chars.forEach((ch, i) => {
      if (i > 0) {
        for (let k = 0; k < GAP; k++) {row.push(0);}
      }

      for (let c = 0; c < GLYPH_W; c++) {row.push((ch[r] >> c) & 1);}
    });
    px.push(row);
  }

  const out: string[] = [];

  for (let y = 0; y < px.length; y += 2) {
    let line = '';

    for (let x = 0; x < px[y].length; x++) {
      const top = px[y][x];
      const bot = y + 1 < px.length ? px[y + 1][x] : 0;
      line += top && bot ? '█' : top ? '▀' : bot ? '▄' : ' ';
    }

    out.push(line.replace(/ +$/, ''));
  }

  while (out.length > 1 && !out[0].trim()) {out.shift();}

  while (out.length > 1 && !out[out.length - 1].trim()) {out.pop();}

  return out;
};
